export const LANGUAGES = ['zh-CN', 'ja', 'en'];
export function resolveLanguage(saved, browserLanguage = 'en') {
  if (LANGUAGES.includes(saved)) return saved;
  const base = String(browserLanguage).toLowerCase().split(/[-_]/)[0];
  return base === 'zh' ? 'zh-CN' : base === 'ja' ? 'ja' : 'en';
}
export const msg = (key, params = {}) => ({ key, params });
export function translate(language, key, params = {}) {
  const entry = Object.hasOwn(translations, key) ? translations[key] : undefined;
  const template = language === 'zh-CN' ? key : entry?.[language === 'ja' ? 1 : 0] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => {
    const value = params[name];
    return value === undefined ? match : typeof value === 'object' && value !== null && 'key' in value
      ? translate(language, value.key, value.params) : String(value);
  });
}
export class MessageError extends Error {
  constructor(key, params = {}) {
    super(translate('zh-CN', key, params));
    this.localized = msg(key, params);
  }
}
export function errorMessage(error) {
  if (error?.localized) return error.localized;
  const detail = error?.message || String(error);
  return Object.hasOwn(translations, detail) ? msg(detail) : msg('操作失败：{detail}', { detail });
}
